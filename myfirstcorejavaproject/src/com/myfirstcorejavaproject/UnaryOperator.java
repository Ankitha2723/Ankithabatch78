package com.myfirstcorejavaproject;

public class UnaryOperator {

	public static void main(String[] args) {
		int a=20;
		int y=30;
		System.out.println(a--);
		System.out.println(a++);
		System.out.println(y--);
		System.out.println(--y);
		System.out.println(++a);
		System.out.println(a--);
		System.out.println(a);
		System.out.println(y);

	}

}
